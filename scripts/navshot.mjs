import { chromium } from 'playwright';
import { createServer } from 'http';
import { readFile, stat } from 'fs/promises';
import { join, extname } from 'path';
const root = '/home/claude/beginbhv/dist';
const mime = {'.html':'text/html','.css':'text/css','.js':'text/javascript','.png':'image/png','.webp':'image/webp','.svg':'image/svg+xml','.jpg':'image/jpeg','.woff2':'font/woff2'};
const srv = createServer(async (req,res)=>{ let p=decodeURIComponent(req.url.split('?')[0]); if(p.endsWith('/')) p+='index.html'; let f=join(root,p); try{ if((await stat(f)).isDirectory()) f=join(f,'index.html'); }catch{ f=join(root,p+'.html'); } try{ const b=await readFile(f); res.setHeader('Content-Type',mime[extname(f)]||'application/octet-stream'); res.end(b);}catch{res.statusCode=404;res.end('nf');} }).listen(4321);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const pg = await b.newPage({ viewport:{width:1386,height:700} });
await pg.goto('http://localhost:4321/', { waitUntil:'networkidle' }); await pg.waitForTimeout(500);
await pg.screenshot({ path:'/tmp/nav-top.png', clip:{x:0,y:0,width:1386,height:420} });
await pg.hover('.has-sub:nth-child(2) > a'); await pg.waitForTimeout(400);
await pg.screenshot({ path:'/tmp/nav-drop.png', clip:{x:0,y:0,width:1386,height:420} });
await pg.mouse.move(5,600); await pg.evaluate(()=>window.scrollTo(0,900)); await pg.waitForTimeout(500);
await pg.screenshot({ path:'/tmp/nav-scrolled.png', clip:{x:0,y:0,width:1386,height:420} });
await pg.hover('.group.right .has-sub > a'); await pg.waitForTimeout(400);
await pg.screenshot({ path:'/tmp/nav-right.png', clip:{x:0,y:0,width:1386,height:420} });
const m = await b.newPage({ viewport:{width:390,height:800} });
await m.goto('http://localhost:4321/cursussen', { waitUntil:'networkidle' });
await m.click('.burger'); await m.click('.has-sub:nth-child(2) .sub-toggle'); await m.waitForTimeout(400);
await m.screenshot({ path:'/tmp/nav-mobile.png' });
await m.evaluate(()=>window.scrollTo(0,600)); await m.waitForTimeout(300); await m.screenshot({ path:'/tmp/nav-mobile-scrolled.png' });
await b.close(); srv.close();
